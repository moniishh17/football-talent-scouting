"""Generate reports/02_data_feasibility.md and tables from the audit outputs and cached panels.

Run after `python -m research.ingest.audit`, `run_all.sh`, and `python -m research.ingest.crosswalk`.
"""
from __future__ import annotations

import pandas as pd

from research.config import AUDIT, PROCESSED, REPORTS
from research.features import panel as PN


def md(df: pd.DataFrame, floatfmt: str = "{:.2f}") -> str:
    cols = list(df.columns)
    lines = ["| " + " | ".join(map(str, cols)) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    for r in df.itertuples(index=False):
        cells = [floatfmt.format(v) if isinstance(v, float) else str(v) for v in r]
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


def linkage(ps: pd.DataFrame, comp: str, thr: int) -> pd.DataFrame:
    d = ps[(ps.competition == comp) & (ps.minutes >= thr)].copy()
    d["y"] = d.season.str[:4].astype(int)
    rows = []
    for y in sorted(d.y.unique()):
        a, b = d[d.y == y], d[d.y == y + 1]
        if len(b):
            rows.append({"from": a.season.iloc[0], "to": b.season.iloc[0], "n_from": a.player_id.nunique(),
                         "n_to": b.player_id.nunique(), "linked": len(set(a.player_id) & set(b.player_id))})
    return pd.DataFrame(rows)


def main():
    cs = pd.read_csv(AUDIT / "competition_seasons.csv")
    ps = pd.read_csv(AUDIT / "player_seasons_lineup.csv")
    a = pd.read_parquet(PROCESSED / "design_a_player_seasons.parquet")
    cw = pd.read_csv(PROCESSED / "crosswalk.csv")
    out = ["# 02 — Data availability and feasibility audit",
           "", "*Generated by `python -m research.ingest.feasibility` from `data/research/audit/*` and cached StatsBomb files "
           "(source: https://github.com/hudl/open-data, competitions.json fetched 2026-10-09).*", ""]
    big = cs[(cs.matches >= 5)].copy()
    out += ["## 1. Male club competition-seasons with ≥ 5 matches", "",
            "Lineups and event files exist for every listed match (360 data: " + str(int(cs.has_360.sum())) + " seasons, unused). "
            "`players_ge450` counts players with ≥ 450 lineup minutes **within the matches StatsBomb provides**.", "",
            md(big[["competition", "season", "matches", "teams", "date_min", "date_max", "players", "players_ge450", "players_ge900"]]), ""]
    full = big[big.matches >= 300]
    out += ["### Reading the table", "",
            f"* Only {len(full)} club seasons are *complete leagues* (≥ 300 matches): " + ", ".join(f"{r.competition} {r.season}" for r in full.itertuples()) + ". All are 2015/16 – no two consecutive seasons of any complete league exist.",
            "* Every other La Liga season (2004/05–2020/21), Ligue 1 2021/22–2022/23, Bundesliga 2015/16 and 2023/24, and MLS 2023 contain only the matches of **one club** (FC Barcelona, Paris Saint-Germain, Bayer Leverkusen, Inter Miami respectively). In those files only that club's players accumulate meaningful minutes; opponents appear in 1–2 matches.",
            "* **No club season later than Bundesliga 2023/24 / MLS 2023 exists in the open data; no 2025-era men's club data exists.** (UEFA Women's Euro 2025 is the only 2025 competition, and is out of scope.) International tournaments (World Cup 2018/2022, Euro 2020/2024, Copa América 2024, AFCON 2023) are 7-match events four years apart and are not used for training.", ""]
    out += ["## 2. Cross-season linkage (lineup minutes, same competition, StatsBomb `player_id`)", ""]
    for thr in (450, 900):
        lk = linkage(ps, "La Liga", thr)
        out += [f"### La Liga, all teams, both seasons ≥ {thr} min (matches StatsBomb provides)", "", md(lk), ""]
    lk_total = {thr: int(linkage(ps, "La Liga", thr).linked.sum()) for thr in (450, 900)}
    out += [f"Total linked player transitions in La Liga: {lk_total[450]} (≥ 450 min), {lk_total[900]} (≥ 900 min); the large figures around 2014/15–2016/17 come from the single complete season (2015/16) and are **not** usable as player-level pairs because the neighbouring seasons are Barcelona-only.", ""]
    out += ["## 3. Design A cohort (Barcelona-match panel, outfield + GK)", ""]
    g = a[a.minutes >= 450].groupby("season_name").agg(players=("player_id", "nunique"), outfield=("position_group", lambda s: int((s != "GK").sum())),
                                                    age_known=("age", lambda s: int(s.notna().sum()))).reset_index()
    out += [md(g), ""]
    k = a[(a.minutes >= 450) & (a.position_group != "GK")][["player_id", "season_year", "age"]]
    pairs = k.merge(k.assign(season_year=k.season_year - 1), on=["player_id", "season_year"], suffixes=("", "_n"))
    pairs_age = pairs[pairs.age.notna()]
    out += [f"Outfield linked pairs (t, t+1), both ≥ 450 min: **{len(pairs)}**; with Transfermarkt-derived age: **{len(pairs_age)}** (pairs for 2004/05-2020/21; unique players {pairs.player_id.nunique()}).",
            "Position groups (player-seasons ≥ 450 min): " + ", ".join(f"{p}={n}" for p, n in a[a.minutes >= 450].position_group.value_counts().items()) + ".", ""]
    # exposure sensitivity
    rows = []
    for thr in (270, 450, 900):
        kk = a[(a.minutes >= thr) & (a.position_group != "GK")][["player_id", "season_year"]]
        rows.append({"min_minutes": thr, "outfield_player_seasons": len(kk),
                     "linked_pairs": len(kk.merge(kk.assign(season_year=kk.season_year - 1), on=["player_id", "season_year"]))})
    out += ["### Exposure-threshold sensitivity (same threshold on both seasons)", "", md(pd.DataFrame(rows)), ""]
    # attrition
    k2 = a[(a.minutes >= 450) & (a.position_group != "GK")][["player_id", "season_year"]]
    last = a.season_year.max()
    k2 = k2[k2.season_year < last]
    kn = a[(a.minutes >= 450)][["player_id", "season_year"]]
    k2 = k2.merge(kn.assign(season_year=kn.season_year - 1).assign(has_next=1), on=["player_id", "season_year"], how="left")
    out += [f"**Attrition**: of {len(k2)} outfield player-seasons (≥ 450 min, excluding the last season) {int(k2.has_next.sum())} ({100*k2.has_next.sum()/len(k2):.0f} %) have a next-season observation ≥ 450 min. "
            "Players who leave Barcelona vanish (only ≤ 2 matches vs Barcelona remain), so the next-season outcome is observed only for retained players: **outcomes are missing not at random** (see `05_results.md` §Attrition).", ""]
    # missing rates
    keyf = ["age", "pass_completion", "shot_accuracy", "xg_per_shot", "dribble_success", "avg_pass_length", "gk_save_pct", "team_poss"]
    mr = pd.DataFrame({"feature": keyf, "missing_rate_pct": [100 * a[a.minutes >= 450][c].isna().mean() for c in keyf]})
    out += ["## 4. Missing-feature rates (Design A, ≥ 450 min)", "", md(mr, "{:.1f}"),
            "Event counts are never missing; ratio features are NaN when the denominator is 0 (e.g. goalkeepers have no dribbles). `age` is missing where the crosswalk has no tier-A match (mostly pre-2012 players absent from the Transfermarkt snapshot).", ""]
    # crosswalk
    out += ["## 5. Player identity and Transfermarkt linkage", "",
            "StatsBomb `player_id` is stable across seasons and competitions and is the only identity key used for linking seasons. Birth dates and market values come from `../transfermkt` via `research/ingest/crosswalk.py` (name tokens + club evidence; see its docstring).", "",
            md(cw.tier.value_counts().rename_axis("tier").reset_index(name="players")), ""]
    cwA = a[(a.minutes >= 450)]
    out += [f"Design A (≥ 450 min): {100*cwA.tm_id.notna().mean():.0f} % of player-seasons have a tier-A link ({int(cwA.tm_id.notna().sum())}/{len(cwA)}).", ""]
    # valuations
    val = PN.load_valuations()
    av = PN.attach_valuation(cwA[cwA.tm_id.notna()].copy(), val)
    nt = av[av.value_t.notna()]
    out += ["## 6. Transfermarkt valuation labels (secondary target)", "",
            f"* Local snapshot: {len(val):,} valuations, {val.tm_id.nunique():,} players, {val.date.min().date()} – {val.date.max().date()}; dated observations, in EUR; **no StatsBomb IDs**.",
            f"* Design A player-seasons with a tier-A link: {len(av)}; with a valuation ≤ 200 days before the season end (`value_t`): {len(nt)}; with both `value_t` and a valuation within ±120 days of +12 months (`value_future`): {int((av.value_t.notna() & av.value_future.notna()).sum())}.",
            "* Licence/permission: the CSVs are a public re-publication of Transfermarkt data. The user supplied them locally; they are used only for non-commercial research, are not copied into any output table beyond derived log-ratios and are not redistributed. **The user should confirm that this use satisfies their obligations under Transfermarkt's terms** before publication.", ""]
    out += ["## 7. What each season can be used for", "",
            "| Role | Seasons | Why |", "|---|---|---|",
            "| Training / development (selection) | Barcelona-match panel, scouting seasons 2004/05–2014/15 (targets 2005/06–2015/16) | Chronologically earliest; first test transition has ≥ 5 training transitions. |",
            "| Held-out confirmation | scouting seasons 2015/16–2019/20 (targets 2016/17–2020/21) | Never used for selecting models/features. |",
            "| Latest-season candidate scoring | La Liga 2020/21 (Barcelona matches) – targets (2021/22) are *not* in the open data; optional out-of-domain scoring of Ligue 1 2022/23 (PSG) and Bundesliga 2023/24 (Leverkusen) | Latest club seasons StatsBomb provides. Predictions cannot be evaluated. |",
            "| Within-season Design B | 2015/16 La Liga, Premier League, Serie A, Ligue 1 (complete leagues) | Only complete multi-league data; horizon is half a season, not a season. |",
            "| Offline fixture / regression tests | World Cup 2022 CSV (legacy) | Single tournament; not used for training. |", ""]
    path = REPORTS / "02_data_feasibility.md"
    path.write_text("\n".join(out), encoding="utf-8")
    print("wrote", path)


if __name__ == "__main__":
    main()
