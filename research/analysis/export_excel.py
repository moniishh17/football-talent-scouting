"""Export the research tables and candidate lists to one Excel workbook (reports/ScoutIQ_research_results.xlsx).
Kept outside data/results because the legacy pipeline archives everything in that folder."""
import pandas as pd
from openpyxl.styles import Font, PatternFill
from openpyxl.utils import get_column_letter

from research.config import REPORTS

T = REPORTS / "tables"
SHEETS = [("Design A main", T / "A_main.csv"), ("Design A paired", T / "A_paired.csv"), ("Design A ablation", T / "A_ablation.csv"),
          ("Design A folds", T / "A_folds.csv"), ("Design A ranking", T / "A_ranking.csv"), ("Design B main", T / "B_main.csv"),
          ("Design B paired", T / "B_paired.csv"), ("Design B ablation", T / "B_ablation.csv"), ("Design B ranking", T / "B_ranking.csv"),
          ("Valuation main", T / "V_main.csv"), ("Valuation paired", T / "V_paired.csv"), ("Valuation ablation", T / "V_ablation.csv"),
          ("Sensitivity", T / "sensitivity.csv"), ("Target sensitivity", T / "target_sensitivity.csv"),
          ("Coverage intervals", T / "uncertainty_coverage.csv"), ("Errors by subgroup", T / "error_by_subgroup.csv"),
          ("Candidates in-domain", REPORTS / "candidates_in_domain_la_liga_2020_21.csv"),
          ("Candidates OOD (unvalidated)", REPORTS / "candidates_out_of_domain.csv")]
NOTE = ["ScoutIQ Research results workbook (generated by research/analysis/export_excel.py).",
        "Sources: StatsBomb Open Data (credit StatsBomb); Transfermarkt snapshot used only for derived age/valuation labels.",
        "Selection of models used the DEVELOPMENT period only; 'confirm' columns are held-out. Intervals are 95% player-cluster bootstrap.",
        "Candidate tables are model outputs for research review: they do not prove any prediction is correct. See reports/05_results.md."]


def main():
    out = REPORTS / "ScoutIQ_research_results.xlsx"
    with pd.ExcelWriter(out, engine="openpyxl") as xw:
        pd.DataFrame({"README": NOTE}).to_excel(xw, "README", index=False)
        for name, path in SHEETS:
            if path.exists():
                df = pd.read_csv(path)
                df.to_excel(xw, name[:31], index=False)
                ws = xw.sheets[name[:31]]
                for c in ws[1]:
                    c.font = Font(bold=True, color="FFFFFF"); c.fill = PatternFill("solid", fgColor="17324D")
                for i, col in enumerate(df.columns, 1):
                    w = min(60, max(10, int(df[col].astype(str).str.len().quantile(0.9)) + 2, len(str(col)) + 2))
                    ws.column_dimensions[get_column_letter(i)].width = w
                ws.freeze_panes = "A2"
    print("wrote", out)


if __name__ == "__main__":
    main()
